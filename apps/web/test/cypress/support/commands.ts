Cypress.Commands.add('login_demo', () => {
  cy.visit('/visitor/login');
  cy.fixture('demo_user').then((user) => {
    cy.get('[name=email]').type(user.email);
    cy.get('[name=password]').type(user.password);
    cy.get('form').submit();
    cy.get('header').should('be.visible');
  });
});

